#!/usr/bin/env python3
"""Gate C11 phase 0: recount the pre-committed expectations of E6-E9, E7-T4 and H1 from the gate reports (read-only) and write consolidation/EXPECTATION_COUNT.md.
Outcome words are matched in the report row/line of each expectation: HELD (incl. 'held, weakly'), FAILED, not scored/unscored, WITHDRAWN."""
import re
R = "results/analysis/"
SRC = [("E6", "gate_e/GATE_E6_REPORT.md", r"^\| (X\d) \|"), ("E7", "gate_e/GATE_E7_REPORT.md", r"^\| (X[A-C]\d?) \|"), ("E8", "gate_e/GATE_E8_REPORT.md", r"^\| (XS\d) \|"),
       ("E9", "gate_e/GATE_E9_REPORT.md", r"^\| (Y\d) \|"), ("E7-T4", "t4/GATE_E7T4_REPORT.md", r"^\| \*\*(X[A-C])\*\*"), ("H1", "gate_e/GATE_H1_REPORT.md", r"^- \*\*(Y\d)\*\*")]
def outcome(line):
    l = line.lower()
    if "withdrawn" in l: return "WITHDRAWN"
    if "not scored" in l or "unscored" in l: return "UNSCORED"
    if "failed" in l: return "FAILED"
    if "held" in l: return "HELD"
    return "UNKNOWN"
rows = []
for gate, f, pat in SRC:
    seen = set()
    for n, line in enumerate(open(R + f), 1):
        m = re.match(pat, line)
        if m and m.group(1) not in seen:
            seen.add(m.group(1)); rows.append((gate, m.group(1), outcome(line), f"results/analysis/{f}:{n}"))
from collections import Counter
c = Counter(r[2] for r in rows)
claim = {"HELD": 20, "FAILED": 4, "UNSCORED": 1, "WITHDRAWN": 1}
match = all(c.get(k, 0) == v for k, v in claim.items()) and c.get("UNKNOWN", 0) == 0
md = ["# Expectation count (Gate C11 phase 0; generated by `tests/c11_expectation_count.py`)", "", "| gate | id | outcome | report file:line |", "|---|---|---|---|"] + [f"| {g} | {i} | {o} | `{s}` |" for g, i, o, s in rows]
md += ["", f"**Totals recounted from the reports:** {c.get('HELD',0)} held, {c.get('FAILED',0)} failed, {c.get('UNSCORED',0)} unscored, {c.get('WITHDRAWN',0)} withdrawn ({len(rows)} expectations; unknown: {c.get('UNKNOWN',0)}).",
       f"**Section V's `[CHECK]` line (20 held, 4 failed, 1 unscored, 1 withdrawn): {'MATCHES' if match else 'DIFFERS'}.**"]
open("results/analysis/consolidation/EXPECTATION_COUNT.md", "w").write("\n".join(md) + "\n"); print("\n".join(md[-3:]))
