#!/usr/bin/env python3
"""C22 S-7: full test tables for the supplement, in the style of paper/tables/t_e8.tex: E7 on both GPUs (with MWU p and Holm-adjusted p), H1 and H2. Every value is read from the gates' CSVs; the evidence id of
each row is the trailing % comment. Writes paper/tables/t_e7_full.tex, t_h1.tex, t_h2.tex and paper/tables/TABLES_C22.md (captions). Not wired into supplementary.tex."""
import csv
rd = lambda p: list(csv.DictReader(open(p)))   # noqa: E731
GE = "results/analysis/gate_e"
def sgn(x, nd=2):
    return ("$-$" if x < 0 else "+") + f"{abs(x):.{nd}f}"
def pv(p):
    m, e = f"{p:.2e}".split("e"); return f"{m}e{int(e)}"
def holm(ps):
    m = len(ps); order = sorted(range(m), key=lambda i: ps[i]); adj = [0.0] * m; run = 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (m - rank) * ps[i])); adj[i] = run
    return adj
NAMES = {"stencil": "Stencil-24K", "stencil8k": "Stencil-8K", "sweep4k": "Sweep-4K", "sweep16k": "Sweep-16K", "stream": "STREAM", "sgemm": "SGEMM", "cufft": "cuFFT", "graphbfs": "GraphBFS-23", "oversub": "Stencil, oversubscribed"}
ORDER = list(NAMES)
# ---- E7, both GPUs
hdr = ["\\begin{tabular}{@{}llllrrrrrcr@{}}", "\\toprule", "GPU & Family & Workload & Thr. & Median $t51$ (s) & Median arm (s) & $\\Delta$ (\\%) & MWU $p$ & Holm $p$ & Sig. & MDE (\\%) \\\\", "\\midrule"]
t = list(hdr)
for gpu, d, pre in (("RTX 5070 Ti", f"{GE}/e7", "E7"), ("Tesla T4", "results/analysis/t4", "T4")):
    first = True
    for fam in ("A", "B"):
        rows = rd(f"{d}/family_{fam.lower()}.csv"); adj = holm([float(r["p"]) for r in rows])
        order = sorted(range(len(rows)), key=lambda i: (ORDER.index(rows[i]["workload"]), rows[i]["arm"]))
        for i in order:
            r = rows[i]
            t.append(f"{gpu if first else ''} & {fam} & {NAMES[r['workload']]} & {r['arm'].replace('stock-', '')} & {float(r['median_base']):.3f} & {float(r['median_c6']):.3f} & {sgn(float(r['delta_pct']))} & {pv(float(r['p']))} & {pv(adj[i])} & {'yes' if r['holm_sig'] == 'True' else 'no'} & {float(r['mde_family_pct']):.2f} \\\\ % {pre}.{fam}.{r['workload']}.{r['arm']}_vs_{r['base']}")
            first = False
    t.append("\\midrule" if gpu == "RTX 5070 Ti" else "")
t = [x for x in t if x != ""] + ["\\bottomrule", "\\end{tabular}", ""]
open("paper/tables/t_e7_full.tex", "w").write("\n".join(t))
# ---- H1
h1 = rd(f"{GE}/h1/h1_tests.csv"); adj = holm([float(r["p"]) for r in h1])
t = ["\\begin{tabular}{@{}lllrrrrcr@{}}", "\\toprule", "Workload (HMM) & Thr. & Median $t51$ (s) & Median arm (s) & $\\Delta$ (\\%) & MWU $p$ & Holm $p$ & Sig. & MDE (\\%) \\\\", "\\midrule"]
HN = {"stencil": "Stencil-24K", "in_k512": "Sparse in memory, $K=512$", "in_k1": "Sparse in memory, $K=1$"}
for i, r in enumerate(h1):
    t.append(f"{HN[r['workload']]} & {r['arm'].replace('stock-', '')} & {float(r['median_base']):.3f} & {float(r['median_c6']):.3f} & {sgn(float(r['delta_pct']))} & {pv(float(r['p']))} & {pv(adj[i])} & {'yes' if r['holm_sig'] == 'True' else 'no'} & {float(r['mde_family_pct']):.2f} \\\\ % H1.{r['workload']}.stock-t0_vs_stock-t51")
t += ["\\bottomrule", "\\end{tabular}", ""]
open("paper/tables/t_h1.tex", "w").write("\n".join(t))
# ---- H2
h2 = rd(f"{GE}/h2/h2_tests.csv"); adj = holm([float(r["p"]) for r in h2])
t = ["\\begin{tabular}{@{}llrrrrrrcr@{}}", "\\toprule", "Allocator & $K$ & Median $t51$ (s) & Median $t0$ (s) & $\\Delta$ (\\%) & MWU $p$ & Holm $p$ & MDE (\\%) & Sig. & Cohen's $d$ \\\\", "\\midrule"]
for i, r in enumerate(h2):
    t.append(f"{'managed' if r['alloc'] == 'managed' else 'HMM (malloc)'} & {r['K']} & {float(r['median_base']):.3f} & {float(r['median_c6']):.3f} & {sgn(float(r['delta_pct']))} & {pv(float(r['p']))} & {pv(adj[i])} & {float(r['mde_family_pct']):.2f} & {'yes' if r['holm_sig'] == 'True' else 'no'} & {sgn(float(r['cohen_d']), 1)} \\\\ % H2.{r['alloc']}_k{r['K']}.t0_vs_t51")
t += ["\\bottomrule", "\\end{tabular}", ""]
open("paper/tables/t_h2.tex", "w").write("\n".join(t))
open("paper/tables/TABLES_C22.md", "w").write("""# Supplementary tables added in C22 (S-7; generated by `tests/c22_supp_tables.py`; not yet wired into `supplementary.tex`)

| table | fragment | source CSV(s) | draft caption |
|---|---|---|---|
| T-E7-FULL | `paper/tables/t_e7_full.tex` | `gate_e/e7/family_a.csv`, `family_b.csv`, `t4/family_a.csv`, `t4/family_b.csv` | Stock driver, thresholds 0, 10 and 25 against the shipped 51, on the RTX 5070 Ti (E7: Family A, 2 tests; Family B, 16 tests) and the Tesla T4 (E7-T4: Family A, 2 tests; Family B, 14 tests); every comparison of both platforms, analysed separately. delta is (arm - t51) / t51; two-sided Mann-Whitney U, n = 10 per cell; Holm p is adjusted within the family; MDE at the family alpha. |
| T-H1 | `paper/tables/t_h1.tex` | `gate_e/h1/h1_tests.csv` | H1 Amendment 1, system-allocated (HMM, malloc) memory, in memory, RTX 5070 Ti: threshold 0 against 51 on Stencil-24K and the sparse benchmark at K = 512 and K = 1. Two-sided Mann-Whitney U, one Holm family of 3, n = 10 per cell; MDE at the family alpha. |
| T-H2 | `paper/tables/t_h2.tex` | `gate_e/h2/h2_tests.csv` | H2, sparse benchmark, 8 GiB in memory, managed against system-allocated (HMM) memory: threshold 0 against 51 for K = 1, 8, 64 and 512. Two-sided Mann-Whitney U, one Holm family of 8, n = 10 per cell; MDE at the family alpha; Cohen's d of the two cells. |
""")
print(len(open("paper/tables/t_e7_full.tex").read().split("\n")), "e7 lines")
